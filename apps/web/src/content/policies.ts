/** The repository file for one policy: what `pnpm policies` writes and the test checks. */
export function policyMarkdown(policy: Policy): string {
  const lines = [
    `# ${policy.title}`,
    '',
    `<!-- Generated from apps/web/src/content/policies.ts by \`pnpm policies\`. Edit there, not here. -->`,
    '',
  ];
  for (const section of policy.sections) {
    lines.push(`## ${section.heading}`, '');
    for (const paragraph of section.body) lines.push(paragraph, '');
  }
  lines.push(
    `Last updated ${POLICIES_UPDATED}. This is plain-language text, not legal advice; it has not yet been reviewed by a lawyer.`,
    '',
  );
  return lines.join('\n');
}
