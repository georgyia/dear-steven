/** Whoever runs this copy, as the legal notice and the privacy notice name them. */
export interface Operator {
  /** A person's full name, or an organisation's name and who represents it. */
  name: string;
  /** A postal address that reaches them, one line each: street, postcode and town, country. */
  address: string[];
  email: string;
}

/**
 * Who runs this copy (#116): the controller in the privacy notice and the legal notice at
 * `/legal`. Not decided yet: the owner fills this in, and until then every place that would show
 * it says so, as for `CONTACT`.
 */
export const OPERATOR: Operator | null = null;
export const OPERATOR_PENDING =
  'TODO (owner): the name, postal address and email address of whoever runs this copy will be published here.';

export interface PolicySection {
  heading: string;
  /** Paragraphs; `[text](url)` links are the only markup. */
  body: string[];
}

export interface Policy {
  file: 'DISCLAIMER.md' | 'TERMS.md' | 'PRIVACY.md';
  title: string;
  sections: PolicySection[];
}

const contact = () => (CONTACT ? `Write to ${CONTACT}.` : CONTACT_PENDING);

/** Who runs this copy, in one line, or the pending note while there are no details yet. */
export function operatorLine(operator: Operator | null = OPERATOR): string {
  if (!operator) return OPERATOR_PENDING;
  return `${operator.name}, ${operator.address.join(', ')}. Email: ${operator.email}.`;
}

